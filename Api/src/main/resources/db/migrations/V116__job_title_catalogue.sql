/*
  THE JOB TITLE CATALOGUE: a vocabulary the picker can offer before anybody types it.

  Why this table exists. Suggestions are derived today from titles already attached to a
  live manager, which works for `chief executive officer` with 636 of them behind it and
  is useless for a sector with no rows yet: nobody is offered `Head Nurse` until somebody
  has already typed `Head Nurse`, and the second nurse then gets whatever spelling the
  first one happened to use. A product that covers every role cannot bootstrap a sector
  from its own submissions.

  Why it is curated rather than imported. O*NET 31.0's Job Titles file was measured
  against a sample of this directory's real titles on 2026-11-25 and matched 46%. The
  misses were not obscure: Vice President, VP, Senior Vice President, SVP, Chairman,
  Manager, Senior Manager, Managing Director, Director of Operations, Assistant Vice
  President, Head Nurse. The reason is structural. O*NET indexes OCCUPATIONS, so a title
  naming what somebody does is present (Store Manager, Nursing Assistant, Software
  Engineer) and a title naming only where they sit is absent, because a Vice President
  could be in any function and maps to no single occupation code. This directory is
  mostly the second kind, so an import would have delivered a picker that cannot suggest
  its own commonest title.

  AN ACRONYM ON MORE THAN ONE ROW IS THE AMBIGUITY, AND THAT IS DELIBERATE.

  `acronym` is not unique. AVP appears on both Assistant Vice President and Associate
  Vice President; PM on Product, Project and Program Manager; CMO on Chief Marketing and
  Chief Medical Officer. Typing the letters offers every reading and the person says which
  they meant, which is the only resolution that guesses nothing. V49 currently resolves
  AVP to Assistant silently, merging two different jobs; this is the machinery that
  replaces that guess with a question.

  `acronym` is a SEARCH KEY AND NEVER A DISPLAY VALUE. The card shows `title`, the
  extended form, because that is the decision taken on 2026-11-25: expand where the
  reading is known, leave the acronym alone only where it genuinely is not.

  No row here is a manager, a company or a rating. Seeding a vocabulary creates no
  profile, touches no count and appears in no statistic. "seed" elsewhere in this schema
  means a platform-created manager (external_id LIKE 'seed_%%'); this is not that.
*/

CREATE TABLE job_titles (
    id          BIGSERIAL PRIMARY KEY,
    title       TEXT        NOT NULL,
    /* The short form, for matching only. Repeated across rows where it is ambiguous. */
    acronym     TEXT,
    /*
      Grouping and search. Computed with the same function managers.title_normalized
      uses, so a catalogue entry and a live title compare on equal terms. It must be
      recomputed if that normalizer changes, which is the pending work to drop V49's
      twelve unsafe expansions.
    */
    match_key   TEXT        NOT NULL,
    source      TEXT        NOT NULL DEFAULT 'curated',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT job_titles_title_key   UNIQUE (title),
    CONSTRAINT job_titles_title_set   CHECK (length(btrim(title)) > 0),
    CONSTRAINT job_titles_source_set  CHECK (source IN ('curated', 'onet', 'noc', 'promoted'))
);

COMMENT ON TABLE  job_titles IS
    'Vocabulary the title picker offers before any manager carries the title. Not managers.';
COMMENT ON COLUMN job_titles.acronym IS
    'Short form, a search key only and never displayed. Non-unique on purpose: a repeated acronym is an ambiguity the picker resolves by asking.';

/* The picker matches on substrings, and pg_trgm is already installed (V55). */
CREATE INDEX job_titles_match_key_trgm ON job_titles USING gin (match_key gin_trgm_ops);
CREATE INDEX job_titles_title_trgm     ON job_titles USING gin (lower(title) gin_trgm_ops);
/* Typing CEO has to resolve, case-insensitively, and most rows have no acronym. */
CREATE INDEX job_titles_acronym        ON job_titles (upper(acronym)) WHERE acronym IS NOT NULL;

